// Helper: split a response string into an array of chunks for streaming simulation
export function chunkDemoReply(text: string): string[] {
  const chunks: string[] = [];
  let i = 0;
  while (i < text.length) {
    // Simulate natural chunk sizes: words, punctuation, line breaks
    const lookAhead = text.slice(i, i + 12);
    const nextBreak = Math.min(
      ...[
        lookAhead.indexOf(" ") + 1,
        lookAhead.indexOf("\n") + 1,
        lookAhead.indexOf("。") + 1,
        lookAhead.indexOf("，") + 1,
        lookAhead.indexOf("、") + 1,
        lookAhead.indexOf("？") + 1,
        lookAhead.indexOf("！") + 1,
      ].filter((n) => n > 0),
      12,
    );

    const chunkSize = nextBreak > 0 ? nextBreak : 3;
    chunks.push(text.slice(i, i + chunkSize));
    i += chunkSize;
  }
  return chunks;
}
